/** 길쭉함을 말로 */
export function ratioWord(r) {
  if (r < 1.2) return '네모에 거의 가까운 땅입니다';
  if (r < 1.5) return '약간 길쭉한 정도입니다';
  if (r < 2) return '한쪽으로 분명히 늘어나 있습니다';
  if (r < 2.8) return '꽤 길게 누운 땅입니다';
  return '띠처럼 가늘고 길게 뻗었습니다';
}
/** 긴 변 길이를 말로 */
export function longWord(m) {
  if (m < 1200) return '끝에서 끝까지 걸어도 금방입니다';
  if (m < 2500) return '한 변이 걸어서 삼십 분쯤 되는 길이입니다';
  if (m < 5000) return '긴 쪽은 차로 움직이는 편이 낫습니다';
  if (m < 12000) return '같은 이름 안인데도 긴 쪽 끝과 끝이 꽤 멉니다';
  return '이름 하나에 묶여 있을 뿐 긴 쪽은 다른 동네만큼 떨어져 있습니다';
}
/** 네모를 채운 몫 */
export function fillWord(f) {
  if (f >= 80) return '감싼 네모를 거의 빈틈없이 채웁니다';
  if (f >= 65) return '네모 안을 넉넉히 채운 모양입니다';
  if (f >= 50) return '모서리 쪽이 제법 비어 있습니다';
  if (f >= 35) return '가장자리가 깊이 파여 네모의 절반 남짓만 찹니다';
  return '네모 안을 성기게 채운, 갈래가 많은 모양입니다';
}
/** 구 안에서 방향이 얼마나 몰려 있는가 */
export function concWord(c) {
  if (c >= 60) return '칸들이 거의 한 방향으로 나란히 누워 있습니다';
  if (c >= 40) return '한 방향으로 모이는 기운이 뚜렷합니다';
  if (c >= 22) return '얼추 비슷한 쪽으로 기울어 있습니다';
  if (c >= 10) return '방향이 제각각인 편입니다';
  return '칸마다 누운 쪽이 다 달라 한 방향으로 묶이지 않습니다';
}
/** 두 칸의 방향 차 */
export function diffWord(d) {
  if (d <= 5) return '거의 나란합니다';
  if (d <= 18) return '비슷한 쪽으로 누웠습니다';
  if (d <= 40) return '조금 틀어져 있습니다';
  if (d <= 70) return '방향이 꽤 어긋납니다';
  return '거의 직각으로 엇갈립니다';
}
